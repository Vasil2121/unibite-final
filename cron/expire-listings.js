/* ===========================================================================
 * cron/expire-listings.js — ΠΕΡΙΟΔΙΚΗ ΕΡΓΑΣΙΑ: ΛΗΞΗ ΑΓΓΕΛΙΩΝ
 * -------------------------------------------------------------------------
 * ΤΙ ΕΙΝΑΙ ΕΡΓΑΣΙΑ CRON
 *   Πρόγραμμα που ΔΕΝ ξεκινάει από αίτημα χρήστη, αλλά εκτελείται σε τακτά
 *   διαστήματα. Τρέχει, κάνει τη δουλειά του, κλείνει.
 *
 * ΤΙ ΚΑΝΕΙ
 *   Σημαδεύει ως 'deleted' όσες αγγελίες πέρασαν το expires_at (48 ώρες από τη
 *   δημιουργία).
 *
 * ΕΚΤΕΛΕΣΗ:  npm run cron:expire
 *
 * ΓΙΑΤΙ ΧΡΕΙΑΖΕΤΑΙ, ΑΦΟΥ ΤΑ QUERIES ΗΔΗ ΦΙΛΤΡΑΡΟΥΝ ΜΕ expires_at > NOW()
 *   Το φιλτράρισμα κρύβει τις ληγμένες από τον χρήστη, αλλά η κατάσταση στη βάση
 *   παραμένει 'active' — δηλαδή τα δεδομένα λένε ψέματα. Το cron συμμαζεύει την
 *   πραγματικότητα, κρατάει τα στατιστικά σωστά και τα queries γρήγορα.
 *
 * ΤΟ pool.end() ΕΙΝΑΙ ΑΠΑΡΑΙΤΗΤΟ
 *   Χωρίς αυτό η διεργασία δεν τερματίζει ποτέ: το pool κρατάει ανοιχτές
 *   συνδέσεις και ο Node θεωρεί ότι έχει ακόμη δουλειά.
 * =========================================================================
 */

import 'dotenv/config';
import pool from '../src/database/connection.js';
import * as listingsStore from '../src/store/listings-store.js';

const expiredCount = await listingsStore.markExpiredAsDeleted();

console.log(`Έληξαν και σημάνθηκαν ως διαγραμμένες: ${expiredCount} αγγελίες`);

await pool.end();
process.exit(0);
